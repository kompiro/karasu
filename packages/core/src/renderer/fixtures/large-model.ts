// A large synthetic model, so a check that needs a model of real-world size has
// one every checkout can make (#3668). The defaults give about 10k lines, the
// size of the reverse-engineered models earlier measurements used (#2757). The
// output is the same on every call: names and edges come from the indexes alone,
// so a number measured on it can be measured again.
//
// Each service holds domains, each domain holds use cases that touch the
// service's own tables and a shared queue, and services call later services at
// fixed strides, so edges cross the drill-down levels.
//
// `pnpm bench:large-model <dir>` writes it to a file for manual steps and
// `pnpm bench:render`.

export interface LargeModelOptions {
  services: number;
  domainsPerService: number;
  usecasesPerDomain: number;
}

export const DEFAULT_OPTIONS: LargeModelOptions = {
  services: 30,
  domainsPerService: 8,
  usecasesPerDomain: 4,
};

const QUEUES = 6;
/** Each service calls the services this many places after it, so the calls form no cycle. */
const SERVICE_STRIDES = [1, 4, 11];

const pad = (n: number): string => String(n).padStart(2, "0");
const serviceId = (s: number): string => `Service${pad(s)}`;
// Unique across services: a domain id repeated under two services is `domain-dispersal`.
const domainId = (s: number, d: number): string => `Service${pad(s)}Domain${pad(d)}`;
const tableId = (d: number): string => `Table${pad(d)}`;

export function generateLargeModel(options: LargeModelOptions = DEFAULT_OPTIONS): string {
  const { services, domainsPerService, usecasesPerDomain } = options;
  const out: string[] = [];
  const line = (depth: number, text: string): void => {
    out.push(`${"  ".repeat(depth)}${text}`);
  };

  line(0, "// Synthetic large model, generated by `pnpm bench:large-model`. Do not edit by hand.");
  line(0, "system Platform {");
  line(1, 'label "Synthetic platform"');
  line(1, 'description "A generated model of real-world size for manual checks and benchmarks"');
  line(0, "");
  line(1, "user Operator [human] {");
  line(2, 'label "Operator"');
  line(1, "}");
  line(1, "user Customer [human] {");
  line(2, 'label "Customer"');
  line(1, "}");
  line(1, "client WebConsole [web] {");
  line(2, 'label "Web console"');
  line(1, "}");

  for (let s = 1; s <= services; s++) {
    line(0, "");
    line(1, `service ${serviceId(s)} {`);
    line(2, `label "Service ${pad(s)}"`);
    line(2, `description "Generated service ${s} of ${services}"`);
    for (let d = 1; d <= domainsPerService; d++) {
      line(2, `domain ${domainId(s, d)} {`);
      line(3, `label "Domain ${pad(s)}-${pad(d)}"`);
      for (let u = 1; u <= usecasesPerDomain; u++) {
        line(3, `usecase UseCase${pad(u)} {`);
        line(4, `label "Use case ${pad(s)}-${pad(d)}-${pad(u)}"`);
        line(4, `resource ${serviceId(s)}DB.${tableId(d)} {`);
        line(5, u === 1 ? "operations read" : "operations create, update");
        line(4, "}");
        line(4, `resource Events.Topic${pad(((s + d + u) % QUEUES) + 1)} {`);
        line(5, u === 1 ? "operations read" : "operations create");
        line(4, "}");
        line(3, "}");
      }
      for (const step of [1, 3]) {
        const target = d + step;
        if (target <= domainsPerService) {
          line(3, `${domainId(s, d)} -> ${domainId(s, target)} "Step ${step}"`);
        }
      }
      line(2, "}");
    }
    line(1, "}");
    line(1, `database ${serviceId(s)}DB {`);
    line(2, `label "Service ${pad(s)} DB"`);
    for (let d = 1; d <= domainsPerService; d++) {
      line(2, `table ${tableId(d)} { label "Table ${pad(d)}" }`);
    }
    line(1, "}");
  }

  line(0, "");
  line(1, "queue Events {");
  line(2, 'label "Events"');
  for (let q = 1; q <= QUEUES; q++) line(2, `queue Topic${pad(q)} { label "Topic ${pad(q)}" }`);
  line(1, "}");

  line(0, "");
  line(1, 'Operator -> WebConsole "Operate"');
  line(1, `Customer -> ${serviceId(1)} "Use"`);
  for (let s = 1; s <= services; s++) {
    if (s % 5 === 1) line(1, `WebConsole -> ${serviceId(s)} "Call"`);
    for (const stride of SERVICE_STRIDES) {
      const target = s + stride;
      if (target <= services) line(1, `${serviceId(s)} -> ${serviceId(target)} "Call +${stride}"`);
    }
  }
  line(0, "}");
  return `${out.join("\n")}\n`;
}
